import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const entryUrl = new URL("../src/plugin/stdio.ts", import.meta.url);
const outputUrl = new URL(
  "../plugin/runtime/dext-fixture-stdio.mjs",
  import.meta.url
);
const checkOnly = process.argv.includes("--check");

const result = await build({
  entryPoints: [fileURLToPath(entryUrl)],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node24",
  packages: "bundle",
  treeShaking: true,
  minify: false,
  sourcemap: false,
  legalComments: "none",
  charset: "utf8",
  banner: {
    js: "// Generated by pnpm build:plugin. Do not edit directly."
  },
  outfile: fileURLToPath(outputUrl),
  write: false
});

const generated = result.outputFiles?.[0]?.contents;
if (!generated) {
  throw new Error("esbuild did not produce the fixture plugin bundle.");
}
const output = Buffer.from(generated)
  .toString("utf8")
  .replace(/^[\t ]+$/gmu, "");

if (checkOnly) {
  const committed = await readFile(outputUrl).catch(() => undefined);
  if (!committed || !Buffer.from(output).equals(committed)) {
    throw new Error(
      "The committed plugin runtime is stale. Run `pnpm build:plugin` and commit the result."
    );
  }
  process.stdout.write("Plugin runtime matches its TypeScript sources.\n");
} else {
  await mkdir(new URL("../plugin/runtime/", import.meta.url), {
    recursive: true
  });
  await writeFile(outputUrl, output, "utf8");
  process.stdout.write(`Built ${fileURLToPath(outputUrl)}\n`);
}
